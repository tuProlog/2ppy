"""Input and output channels backed by Python callables, and their listeners."""

import pytest
from jpype import JException

from tuprolog.solve.channel import (
    Channel,
    InputChannel,
    Listener,
    OutputChannel,
    input_channel,
    listener,
    output_channel,
)


def test_input_channel_from_string():
    channel = input_channel("ab")
    assert isinstance(channel, InputChannel)
    assert isinstance(channel, Channel)
    assert channel.read() == "a"
    assert channel.peek() == "b"
    assert channel.read() == "b"
    assert channel.read() is None
    assert channel.is_over


def test_input_channel_from_empty_string():
    channel = input_channel("")
    assert channel.read() is None
    assert channel.is_over


def test_input_channel_from_generator_function():
    items = iter(["x", "y"])
    channel = input_channel(lambda: next(items, None))
    assert channel.available
    assert [channel.read(), channel.read(), channel.read()] == ["x", "y", None]
    assert channel.is_over


def test_input_channel_with_availability_checker_via_getter():
    channel = input_channel(lambda: "z", lambda: False)
    assert not channel.getAvailable()
    assert channel.read() == "z"


@pytest.mark.xfail(
    strict=True,
    reason="snake_case properties generated by jvmutils (e.g. InputChannel.available, "
    "Solution.exception) do not dispatch to the overriding implementation",
)
def test_input_channel_with_availability_checker():
    calls: list[str] = []

    def available():
        calls.append("checked")
        return False

    channel = input_channel(lambda: "z", available)
    assert not channel.available
    assert calls
    assert channel.read() == "z"


def test_output_channel_forwards_writes():
    written: list[str] = []
    channel = output_channel(written.append)
    assert isinstance(channel, OutputChannel)
    channel.write("a")
    channel.write("b")
    channel.flush()
    assert written == ["a", "b"]


def test_closed_output_channel_rejects_writes():
    channel = output_channel(lambda _: None)
    assert not channel.is_closed
    channel.close()
    assert channel.is_closed
    with pytest.raises(JException):
        channel.write("x")


def test_closed_input_channel():
    channel = input_channel("abc")
    channel.close()
    assert channel.is_closed


def test_listener_is_a_listener():
    assert isinstance(listener(print), Listener)


def test_listener_wraps_python_callables():
    seen: list[str] = []
    listen = listener(seen.append)
    listen.invoke("value")
    assert seen == ["value"]


def test_output_listeners():
    written, seen = [], []
    channel = output_channel(written.append)
    listen = listener(seen.append)
    channel.add_listener(listen)
    channel.write("a")
    channel.remove_listener(listen)
    channel.write("b")
    assert written == ["a", "b"]
    assert seen == ["a"]


def test_clear_listeners():
    seen: list[str] = []
    channel = output_channel(lambda _: None)
    channel.add_listener(listener(seen.append))
    channel.add_listener(listener(seen.append))
    channel.write("a")
    channel.clear_listeners()
    channel.write("b")
    assert seen == ["a", "a"]


def test_input_listeners():
    seen: list[str] = []
    channel = input_channel("ab")
    channel.add_listener(listener(seen.append))
    channel.read()
    channel.read()
    assert seen == ["a", "b"]
