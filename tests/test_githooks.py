import importlib.util
from pathlib import Path

import pytest

_spec = importlib.util.spec_from_file_location(
    "githooks", Path(__file__).parents[1] / "scripts" / "githooks.py"
)
assert _spec and _spec.loader
githooks = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(githooks)


@pytest.mark.parametrize(
    "message,ok",
    [
        ("feat: add a feature", True),
        ("fix(cli)!: drop a flag\n\nbody", True),
        ("# comment\n\nchore(deps): bump ruff", True),
        ("Merge branch 'main'", True),
        ("fixup! feat: x", True),
        ("update stuff", False),
        ("feat:missing space", False),
        ("feature: not a type", False),
        ("", False),
        ("feat: x\n\nCo-Authored-By: Claude Opus 5.5 <noreply@anthropic.com>", False),
        ("feat: x\n\nco-authored-by: Codex <codex@users.noreply.github.com>", False),
        (
            "fix: x\n\n\U0001f916 Generated with [Claude Code](https://claude.com/claude-code)",
            False,
        ),
        ("fix: x\n\nGenerated by GitHub Copilot", False),
        ("feat: x\n\nCo-Authored-By: Jane Doe <jane@example.com>", True),
        ("docs: explain the Claude Code setup", True),
        ("feat: x\n# Co-Authored-By: Claude\n", True),
    ],
)
def test_check_msg(tmp_path, message, ok):
    file = tmp_path / "MSG"
    file.write_text(message, encoding="utf-8")
    assert (githooks.check_msg(str(file)) == githooks.check_ai(str(file)) == 0) is ok


def test_hooks_sharing_commit_msg_install_separately(tmp_path, monkeypatch):
    monkeypatch.setattr(githooks, "hooks_dir", lambda: tmp_path)
    hook = tmp_path / "commit-msg"
    assert githooks.main(["install", "no-ai-signature"]) == 0
    assert githooks.installed(hook) == {"no-ai-signature"}
    assert githooks.main(["install", "conventional-commits"]) == 0
    assert githooks.installed(hook) == {"no-ai-signature", "conventional-commits"}
    assert "check-ai" in hook.read_text() and "check-msg" in hook.read_text()
    assert githooks.main(["uninstall", "no-ai-signature"]) == 0
    assert githooks.installed(hook) == {"conventional-commits"}
    assert "check-ai" not in hook.read_text()


def test_install_uninstall_leave_foreign_hooks(tmp_path, monkeypatch):
    monkeypatch.setattr(githooks, "hooks_dir", lambda: tmp_path)
    (tmp_path / "pre-push").write_text("#!/bin/sh\necho mine\n")
    assert githooks.main(["install"]) == 1
    assert githooks.is_ours(tmp_path / "pre-commit")
    assert githooks.is_ours(tmp_path / "commit-msg")
    assert not githooks.is_ours(tmp_path / "pre-push")
    assert githooks.main(["uninstall", "pre-commit"]) == 0
    assert not (tmp_path / "pre-commit").exists()
    assert githooks.main(["uninstall"]) == 0
    assert not (tmp_path / "commit-msg").exists()
    assert (tmp_path / "pre-push").read_text() == "#!/bin/sh\necho mine\n"
    assert githooks.main(["install", "nope"]) == 2
